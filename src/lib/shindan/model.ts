/* ===== 採点 ===== */
export interface Scores {
  type: Record<string, number>;      // 8タイプ+t9 正規化% (高い=問題が強い)
  verb: Record<VerbKey, number>;     // 完遂力% (高い=強い。問題スコアの逆数)
  load: number;                      // 量の負荷% (t9)
  top: string[];                     // プロセス上位2タイプ
  verdict: "A" | "B" | "C" | "none";
}

export function score(role: Role, answers: number[]): Scores {
  const qs = questionsFor(role);
  const raw: Record<string, number> = {}, max: Record<string, number> = {};
  const vRaw: Record<string, number> = {}, vMax: Record<string, number> = {};
  qs.forEach((q, i) => {
    const a = answers[i] ?? 0;
    for (const [k, w] of Object.entries(q.w)) {
      raw[k] = (raw[k] || 0) + w * a;
      max[k] = (max[k] || 0) + w * 2;
    }
    if (q.verb) {
      vRaw[q.verb] = (vRaw[q.verb] || 0) + a;
      vMax[q.verb] = (vMax[q.verb] || 0) + 2;
    }
  });
  const type: Record<string, number> = {};
  for (const k of Object.keys(max)) type[k] = Math.round(((raw[k] || 0) / max[k]) * 100);
  const verb = {} as Record<VerbKey, number>;
  for (const k of VERB_KEYS) verb[k] = 100 - Math.round(((vRaw[k] || 0) / (vMax[k] || 1)) * 100);
  const load = type.t9 || 0;
  // 同率タイの順位づけ: 素点だと設問数の多いタイプが常に勝ち、高得点層の結果が同じペアに収束する。
  // 回答ベクトルの決定的ハッシュで分散させる（同じ回答→必ず同じ結果。僅かに違う回答→違う並び）
  const hash = (k: string) => {
    const s = k + ":" + answers.join("");
    let x = 0;
    for (let i = 0; i < s.length; i++) x = (x * 31 + s.charCodeAt(i)) | 0;
    return x;
  };
  const sorted = [...PROCESS_KEYS].sort((a, b) => ((type[b] || 0) - (type[a] || 0)) || (hash(b) - hash(a)));
  const top = sorted.slice(0, 2).filter((k) => (type[k] || 0) > 0);
  const P = ((type[sorted[0]] || 0) + (type[sorted[1]] || 0)) / 2;
  const verdict = top.length === 0 && load === 0 ? "none" : load < 50 ? "A" : P >= 40 ? "B" : "C";
  return { type, verb, load, top, verdict };
}

