/**
 * 練習（対話型チュートリアル）で秘書がしゃべる文章。**このファイルが唯一の正本**。
 *
 * 登録が成立したときの文言（claimLimboCore.ts の CODE_ONLY_LINKED_TEXT 等）は
 * セキュリティ上の固定文言なので**1文字も変えない**。ここの文章はその「後ろに足す」だけ。
 *
 * 書き方の約束:
 *   - 打つ文字列は『』で囲み、そのまま真似できる形で書く。区切りの空白も見本どおり入れる。
 *   - 手順はチャットの種類で分けない（ボタンのある LINE でも同じ手順にする＝説明がズレない）。
 *   - 逃げ道（『あとで』）と、いつでも呼べる救急箱（『ヘルプ』）を最初に必ず伝える。
 *   - **言い方は使い方案内（commandGuides.ts）とそろえる**。タスクを終わらせる操作は
 *     「完了にする」で書く（秘書の実際の返事が「『○○』を完了にしました。」だから）。
 *   - **直前の返信と同じ報告を繰り返さない**。登録の報告・完了の報告は呼び出し側が済ませているので、
 *     ここでは「次に何をするか」だけを言う（人が話していれば2度言わない）。
 *   - ただし**直前の返信の文面そのものには寄りかからない**。直前の言い方はチャットごとに違う
 *     （LINE は「タスクに追加しました。」、ほかは「『○○』をお預かりしました。…」）。
 *     どちらでも通じるよう、練習の1通は**単独で読んで分かる**ように書く。
 *   - **合図でない言葉を動詞で誘わない**。「やめるときは『あとで』」と書くと、動詞につられて
 *     『やめる』と打つ人が出るが、『やめる』は合図から外してあるので無反応になる。
 */

/**
 * 練習で作るタスクの名前。
 *
 * ⚠ 中身のある題名（「秘書の使い方をおぼえる」など）にしてはいけない。練習が途中で放置されると、
 *   相手先の一覧にその題名のまま残り、誰も中身を知らないタスクになる。ひと目で使い捨てと
 *   分かる言葉にして、放置されても不安を与えないようにする。
 */
export const TUTORIAL_PRACTICE_TITLE = 'れんしゅう'

/**
 * 登録が成立した直後の導入。ここで練習の入り口を出す。
 *
 * 区切りの空白をわざわざ1行で説明するのは、ここが**最初に打ってもらう合図**だから。
 * 「タスク追加」は空白が無いと読み取れず、いきなり無反応で終わってしまう。
 */
export const TUTORIAL_INTRO_TEXT =
  'はじめまして。このグループのやり取りから、やることを拾ってお預かりします。\n' +
  `せっかくなので、1分だけ練習してみましょう。まず『タスク追加 ${TUTORIAL_PRACTICE_TITLE}』と送ってみてください。\n` +
  '「タスク追加」と内容のあいだに、空白を1つ入れてください。\n' +
  '練習で作るタスクは、このあとすぐ完了にするので残りません。\n' +
  'いま練習しないときは『あとで』、使い方を見たいときは『ヘルプ』と送ってください。'

/**
 * 練習のタスクを預かれたときの案内。番号は採番をやり直して確定させた実物を渡すこと
 * （約束した番号で完了にできなければ練習にならない）。
 *
 * ⚠ **直前の返信の文面に寄りかからない**。以前は「直前が『次にお届けする一覧に載ります』と
 *   言っている」ことを前提に「いま付いた番号は3番です。」とだけ書いていたが、LINE はこの返信を
 *   通らず、直前に出るのは「タスクに追加しました。」だけ（一覧の話をしていない）。
 *   前提が崩れるので、**この1通だけを読んで通じる**形にする＝どのタスクの何番かを自分で名乗る。
 *
 * ⚠ 「一覧」と書かない。打つ合図の名前と、定期的に届くお知らせで意味が割れる
 *   （言葉づかいの正本は commandGuides.ts）。
 */
export function buildTutorialAddedText(digestNumber: number, title: string): string {
  return (
    `「${title}」に${digestNumber}番が付きました。\n` +
    `続けて『完了 ${digestNumber}』と送ってみてください。この番号のタスクを完了にします。`
  )
}

/** 練習のタスクを完了にできたときの締め。完了の報告は直前の返信が済ませている。 */
export const TUTORIAL_COMPLETED_TEXT =
  '練習はここまでです。\n使い方を見たいときは、いつでも『ヘルプ』と送ってください。'

/** 途中でやめたとき。引き止めない。 */
export const TUTORIAL_SKIPPED_TEXT =
  'わかりました。使い方を見たいときは、いつでも『ヘルプ』と送ってください。'
