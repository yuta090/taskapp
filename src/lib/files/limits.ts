/**
 * ファイル一覧の取得件数の上限。
 *
 * 一覧は react-query の永続キャッシュ(IDB)に丸ごと保存されるため、説明文まで含めた
 * 全件を無制限に持つと IDB が肥大し、タスクや受信箱の初回描画まで遅くなる。
 * また一覧は仮想化していないので、描画コストの面でも上限が要る。
 *
 * 上限に達したかどうかは「返ってきた件数 === この値」で判定して画面に伝える
 * (黙って切り捨てると、探しているファイルが無いのか隠れているのか分からなくなる)。
 *
 * 500 は「仮想化なしで耐えられる上限」として決めた値。上限をこれより上げるとき、
 * または実在スペースが常時 500 件に張り付くようになったときは、一覧の仮想化
 * (@tanstack/react-virtual)が必須になる。行は説明文の有無で高さが変わるため
 * measureElement が要り、行高が固定の TasksPageClient より導入の手間がかかる点を
 * 織り込んで判断すること。
 */
export const FILES_LIST_LIMIT = 500
